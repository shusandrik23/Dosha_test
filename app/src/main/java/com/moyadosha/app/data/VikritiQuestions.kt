/** Результат теста на баланс. leading пуст — доши в балансе. */
data class VikritiResult(
    val normCount: Int,
    val counts: Map<Dosha, Int>,
    val total: Int,
    val leading: List<Dosha>,
) {
    val balanced: Boolean get() = leading.isEmpty()
    fun points(d: Dosha) = counts.getValue(d) * 2

    /** Доля ответов в процентах: ключ null — «Норма». В сумме ровно 100. */
    val percents: Map<Dosha?, Int> by lazy {
        val keys: List<Dosha?> = listOf(null) + Dosha.entries
        val raw = keys.associateWith { k ->
            val n = if (k == null) normCount else counts.getValue(k)
            if (total == 0) 0.0 else n * 100.0 / total
        }
        val result = raw.mapValues { it.value.toInt() }.toMutableMap()
        var rest = if (total == 0) 0 else 100 - result.values.sum()
        raw.entries.sortedByDescending { it.value - it.value.toInt() }.forEach {
            if (rest > 0) {
                result[it.key] = result.getValue(it.key) + 1
                rest--
            }
        }
        result
    }
}

object VikritiScoring {
    /** Двойной дисбаланс — если вторая доша отстаёт от первой не больше чем на 1 ответ. */
    private const val DUAL_GAP_ANSWERS = 1

    fun score(answers: List<Dosha?>): VikritiResult {
        val counts = Dosha.entries.associateWith { d -> answers.count { it == d } }
        val norm = answers.count { it == null }
        val sorted = Dosha.entries.sortedByDescending { counts.getValue(it) }
        val top = counts.getValue(sorted[0])
        val second = counts.getValue(sorted[1])
        val leading = when {
            norm >= top -> emptyList()
            top - second <= DUAL_GAP_ANSWERS && second > 0 -> sorted.take(2)
            else -> sorted.take(1)
        }
        return VikritiResult(norm, counts, answers.size, leading)
    }
}
